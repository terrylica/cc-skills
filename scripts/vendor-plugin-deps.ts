#!/usr/bin/env bun
/**
 * vendor-plugin-deps: bundle the third-party runtime packages a plugin CLI imports into ONE committed file, so the CLI
 * runs from any copy of the plugin (the versioned cache, the marketplace clone, a fresh machine) with nothing installed.
 *
 * Why (#91): Claude Code installs a plugin's packages only when "the plugin's root directory contains both a
 * `package.json` and a supported lockfile" (code.claude.com/docs/en/plugins/loading, "Node.js package dependencies").
 * These CLIs keep theirs in sub-folders, so every plugin update left them without node_modules. A vendored bundle is
 * 0.3-0.9 MB against 42-59 MB of node_modules (measured 2026-11-19) and needs no install step at all.
 *
 * Only the third-party code is generated. The CLIs' own sources stay as they are and import from `./vendor/<name>.js`
 * (runtime) and from the package itself for types (`import type`, erased at run time). Native addons cannot be bundled
 * (Bun's bundler treats `.node` files as assets), so a plugin that needs one keeps its package at the plugin root,
 * where Claude Code's own install covers it.
 *
 * Each output starts with a header holding the SHA-256 of its inputs (package.json, bun.lock, the export list). The
 * check compares that hash, not the bundle's bytes, so a newer Bun that emits different code does not fail the gate;
 * a dependency change does. Licenses of every package that went into a bundle are written next to it.
 *
 * PROCESS-STORM-OK: the only child process is one `bun install` per target, awaited one at a time.
 *
 * Usage:
 *   bun scripts/vendor-plugin-deps.ts            rebuild every vendored bundle (needs the registry once)
 *   bun scripts/vendor-plugin-deps.ts --check    exit 1 if a bundle is missing or its inputs changed (offline)
 *   bun scripts/vendor-plugin-deps.ts --only <id> one target
 */
import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";

interface Target {
  /** Short id for --only and messages. */
  id: string;
  /** Folder holding the package.json and bun.lock that pin the dependency. */
  dir: string;
  /** Output file, relative to `dir`. */
  out: string;
  /** The exact runtime exports the CLI uses, as module specifier -> names. Nothing else is bundled. */
  exports: Record<string, string[]>;
}

/** The SSoT of what is vendored. Add a target here, then run the script and commit its output. */
export const TARGETS: Target[] = [
  {
    id: "tlg",
    dir: "plugins/tlg/scripts",
    out: "vendor/telegram.js",
    exports: { telegram: ["Api", "TelegramClient"], "telegram/extensions/Logger": ["Logger", "LogLevel"], "telegram/sessions": ["StringSession"], "big-integer": ["default as bigInt"] },
  },
  {
    id: "gmail",
    dir: "plugins/gmail-commander/scripts/gmail-cli",
    out: "vendor/googleapis-gmail.js",
    exports: { "@googleapis/gmail": ["auth", "gmail"] },
  },
  {
    id: "gdrive",
    dir: "plugins/productivity-tools/skills/gdrive-access/scripts",
    out: "vendor/googleapis-drive.js",
    exports: { "@googleapis/drive": ["auth", "drive"] },
  },
];

/** Bumped when this script's output format changes, so every bundle is rebuilt. */
const FORMAT = 1;
const REPO = resolve(import.meta.dir, "..");
const HEADER_RE = /^\/\/ vendor-plugin-deps inputs-sha256: ([0-9a-f]{64})$/m;
const PACKAGE_IN_PATH = /node_modules\/((?:@[^/]+\/)?[^/]+)\//;

function entrySource(t: Target): string {
  return Object.entries(t.exports)
    .map(([spec, names]) => `export { ${names.join(", ")} } from ${JSON.stringify(spec)};`)
    .join("\n") + "\n";
}

export function inputsHash(t: Target, root = REPO): string {
  const h = createHash("sha256");
  h.update(`format ${FORMAT}\n`);
  for (const f of ["package.json", "bun.lock"]) h.update(`${f}\n`).update(readFileSync(join(root, t.dir, f)));
  h.update(entrySource(t));
  return h.digest("hex");
}

function header(t: Target, hash: string): string {
  return [
    `// vendor-plugin-deps inputs-sha256: ${hash}`,
    `// GENERATED by scripts/vendor-plugin-deps.ts from ${t.dir}/package.json and bun.lock. Do not edit; rebuild it.`,
    `// Third-party code; licenses in ${t.out.replace(/\.js$/, ".LICENSES.txt")}.`,
    "",
  ].join("\n");
}

/** Every package whose files went into the bundle (from Bun's metafile inputs), with its license text. */
function licenseNotice(inputPaths: string[], nodeModules: string): string {
  const names = new Set(inputPaths.map((p) => PACKAGE_IN_PATH.exec(p.replaceAll("\\", "/"))?.[1]).filter((n): n is string => !!n));
  return [...names].toSorted().map((name) => {
    const dir = join(nodeModules, name);
    const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8")) as { version?: string; license?: string };
    const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
    // Absent fields are left out, never replaced by a made-up value.
    const title = `=== ${name}${pkg.version ? `@${pkg.version}` : ""}${pkg.license ? ` (${pkg.license})` : ""}`;
    const text = file ? readFileSync(join(dir, file), "utf8").trim() : "(the package ships no license file; see its package.json license field above)";
    return `${title}\n\n${text}\n`;
  }).join("\n");
}

async function build(t: Target): Promise<void> {
  const work = mkdtempSync(join(tmpdir(), `vendor-${t.id}-`));
  try {
    for (const f of ["package.json", "bun.lock"]) cpSync(join(REPO, t.dir, f), join(work, f));
    // The same constraints Claude Code's own install uses: exact lockfile versions, no lifecycle scripts.
    const install = Bun.spawnSync(["bun", "install", "--frozen-lockfile", "--ignore-scripts"], { cwd: work, stdout: "pipe", stderr: "pipe" });
    if (install.exitCode !== 0) throw new Error(`${t.id}: bun install failed:\n${install.stderr.toString()}`);
    writeFileSync(join(work, "vendor-entry.ts"), entrySource(t));
    const result = await Bun.build({ entrypoints: [join(work, "vendor-entry.ts")], target: "bun", metafile: true });
    if (!result.success) throw new Error(`${t.id}: bundle failed:\n${result.logs.join("\n")}`);
    const code = await result.outputs[0].text();
    const out = join(REPO, t.dir, t.out);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, header(t, inputsHash(t)) + code);
    // Types: re-export the package's own declarations (resolved wherever the package is installed for development).
    writeFileSync(out.replace(/\.js$/, ".d.ts"), `${header(t, inputsHash(t))}${entrySource(t)}`);
    // Same first line as the bundle: the privacy gate recognises generated vendor files by it (they skip only its AI
    // pass, like lockfiles; its deterministic term scan still runs).
    const licenses = licenseNotice(Object.keys(result.metafile?.inputs ?? {}), join(work, "node_modules"));
    writeFileSync(out.replace(/\.js$/, ".LICENSES.txt"), `# vendor-plugin-deps inputs-sha256: ${inputsHash(t)}\n# Licenses of the packages bundled into ${t.out}.\n\n${licenses}`);
    console.log(`${t.id}: ${relative(REPO, out)} (${(code.length / 1024).toFixed(0)} KiB)`);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

/** Problems with the committed bundles, empty when every one is present and current. Offline. */
export function check(targets = TARGETS, root = REPO): string[] {
  const problems: string[] = [];
  for (const t of targets) {
    const out = join(root, t.dir, t.out);
    if (!existsSync(out)) {
      problems.push(`${t.id}: ${t.dir}/${t.out} is missing`);
      continue;
    }
    const recorded = HEADER_RE.exec(readFileSync(out, "utf8").slice(0, 200))?.[1];
    if (recorded !== inputsHash(t, root)) problems.push(`${t.id}: ${t.dir}/${t.out} is stale (its package.json, bun.lock or export list changed)`);
    if (!existsSync(out.replace(/\.js$/, ".d.ts"))) problems.push(`${t.id}: type declarations next to ${t.out} are missing`);
    if (!existsSync(out.replace(/\.js$/, ".LICENSES.txt"))) problems.push(`${t.id}: license notice next to ${t.out} is missing`);
  }
  return problems;
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const only = args.includes("--only") ? args[args.indexOf("--only") + 1] : undefined;
  const targets = only ? TARGETS.filter((t) => t.id === only) : TARGETS;
  if (only && targets.length === 0) {
    console.error(`unknown target ${only}; known: ${TARGETS.map((t) => t.id).join(", ")}`);
    process.exit(2);
  }
  if (args.includes("--check")) {
    const problems = check(targets);
    for (const p of problems) console.error(`✗ ${p}`);
    if (problems.length) {
      console.error("Rebuild: bun scripts/vendor-plugin-deps.ts, then commit the output.");
      process.exit(1);
    }
    console.log(`✓ ${targets.length} vendored bundle(s) current`);
  } else {
    for (const t of targets) await build(t);
  }
}
